using CoroMES.Core.Entities;
using CoroMES.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;

namespace CoroMES.Web.Startup;

public static class DatabaseStartupExtensions
{
    public static async Task EnsureCoroMesDatabaseAsync(this WebApplication app, string dbProvider)
    {
        using var scope = app.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        if (string.Equals(dbProvider, "postgres", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.MigrateAsync();
            await EnsureAuditTableAsync(db, dbProvider);
            await EnsureAlarmEventsTableAsync(db, dbProvider);
            await EnsureSystemSettingsTableAsync(db, dbProvider);
            await EnsureDisplayDefinitionsTableAsync(db, dbProvider);
        }
        else
        {
            await db.Database.EnsureCreatedAsync();
            await EnsureAuditTableAsync(db, dbProvider);
            await EnsureAlarmEventsTableAsync(db, dbProvider);
            await EnsureSystemSettingsTableAsync(db, dbProvider);
            await EnsureDisplayDefinitionsTableAsync(db, dbProvider);
        }

        await SeedDisplayDefinitionsAsync(db);
    }

    private static async Task EnsureAuditTableAsync(ApplicationDbContext db, string dbProvider)
    {
        if (string.Equals(dbProvider, "postgres", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "AuditLogs" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
                    "CreatedAt" timestamp with time zone NOT NULL,
                    "UpdatedAt" timestamp with time zone NULL,
                    "CreatedBy" text NULL,
                    "UpdatedBy" text NULL,
                    "OccurredAtUtc" timestamp with time zone NOT NULL,
                    "Actor" character varying(120) NOT NULL,
                    "Action" character varying(80) NOT NULL,
                    "EntityName" character varying(120) NOT NULL,
                    "EntityId" integer NULL,
                    "Route" character varying(300) NULL,
                    "IpAddress" character varying(80) NULL,
                    "UserAgent" character varying(300) NULL,
                    "Succeeded" boolean NOT NULL,
                    "Summary" character varying(1000) NOT NULL,
                    CONSTRAINT "PK_AuditLogs" PRIMARY KEY ("Id")
                );
                """);
        }
        else
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "AuditLogs" (
                    "Id" INTEGER NOT NULL CONSTRAINT "PK_AuditLogs" PRIMARY KEY AUTOINCREMENT,
                    "CreatedAt" TEXT NOT NULL,
                    "UpdatedAt" TEXT NULL,
                    "CreatedBy" TEXT NULL,
                    "UpdatedBy" TEXT NULL,
                    "OccurredAtUtc" TEXT NOT NULL,
                    "Actor" TEXT NOT NULL,
                    "Action" TEXT NOT NULL,
                    "EntityName" TEXT NOT NULL,
                    "EntityId" INTEGER NULL,
                    "Route" TEXT NULL,
                    "IpAddress" TEXT NULL,
                    "UserAgent" TEXT NULL,
                    "Succeeded" INTEGER NOT NULL,
                    "Summary" TEXT NOT NULL
                );
                """);
        }

        await db.Database.ExecuteSqlRawAsync("""
            CREATE INDEX IF NOT EXISTS "IX_AuditLogs_OccurredAtUtc" ON "AuditLogs" ("OccurredAtUtc");
            """);

        await db.Database.ExecuteSqlRawAsync("""
            CREATE INDEX IF NOT EXISTS "IX_AuditLogs_EntityName_EntityId" ON "AuditLogs" ("EntityName", "EntityId");
            """);
    }

    private static async Task EnsureDisplayDefinitionsTableAsync(ApplicationDbContext db, string dbProvider)
    {
        if (string.Equals(dbProvider, "postgres", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "DisplayDefinitions" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
                    "Slug" character varying(120) NOT NULL,
                    "Name" character varying(160) NOT NULL,
                    "Type" character varying(40) NOT NULL,
                    "RefreshSeconds" integer NOT NULL,
                    "EquipmentId" integer NULL,
                    "IsActive" boolean NOT NULL,
                    "SettingsJson" character varying(4000) NULL,
                    "CreatedAt" timestamp with time zone NOT NULL,
                    "UpdatedAt" timestamp with time zone NULL,
                    "CreatedBy" text NULL,
                    "UpdatedBy" text NULL,
                    CONSTRAINT "PK_DisplayDefinitions" PRIMARY KEY ("Id"),
                    CONSTRAINT "FK_DisplayDefinitions_Equipment_EquipmentId" FOREIGN KEY ("EquipmentId") REFERENCES "Equipment" ("Id") ON DELETE SET NULL
                );
                """);
        }
        else
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "DisplayDefinitions" (
                    "Id" INTEGER NOT NULL CONSTRAINT "PK_DisplayDefinitions" PRIMARY KEY AUTOINCREMENT,
                    "Slug" TEXT NOT NULL,
                    "Name" TEXT NOT NULL,
                    "Type" TEXT NOT NULL,
                    "RefreshSeconds" INTEGER NOT NULL,
                    "EquipmentId" INTEGER NULL,
                    "IsActive" INTEGER NOT NULL,
                    "SettingsJson" TEXT NULL,
                    "CreatedAt" TEXT NOT NULL,
                    "UpdatedAt" TEXT NULL,
                    "CreatedBy" TEXT NULL,
                    "UpdatedBy" TEXT NULL,
                    CONSTRAINT "FK_DisplayDefinitions_Equipment_EquipmentId" FOREIGN KEY ("EquipmentId") REFERENCES "Equipment" ("Id") ON DELETE SET NULL
                );
                """);
        }

        await db.Database.ExecuteSqlRawAsync("""
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_DisplayDefinitions_Slug" ON "DisplayDefinitions" ("Slug");
            """);

        await db.Database.ExecuteSqlRawAsync("""
            CREATE INDEX IF NOT EXISTS "IX_DisplayDefinitions_EquipmentId" ON "DisplayDefinitions" ("EquipmentId");
            """);
    }

