            """);
    }

    private static async Task SeedDisplayDefinitionsAsync(ApplicationDbContext db)
    {
        if (await db.DisplayDefinitions.AnyAsync())
        {
            return;
        }

        db.DisplayDefinitions.AddRange(
            new DisplayDefinition { Slug = "line1-oee", Name = "Line 1 OEE", Type = "oee", RefreshSeconds = 5, IsActive = true },
            new DisplayDefinition { Slug = "quality", Name = "Quality Monitor", Type = "quality", RefreshSeconds = 10, IsActive = true },
            new DisplayDefinition { Slug = "equipment", Name = "Equipment Status", Type = "equipment", RefreshSeconds = 3, IsActive = true });

        await db.SaveChangesAsync();
    }
}
